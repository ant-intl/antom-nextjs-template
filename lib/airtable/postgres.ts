import { AirtableError, mergeEvidenceStatus, type Attempt, type CheckoutSession, type OrderSnapshot, type PaymentEvidence } from './domain';
import type { AttemptStore } from './store';

export interface SqlConnection {
  query(sql: string, values?: unknown[]): Promise<{ rows: Record<string, unknown>[] }>;
}
export interface SqlPool extends SqlConnection {
  connect(): Promise<SqlConnection & { release(): void }>;
}

function attemptFromRow(row: Record<string, unknown>): Attempt {
  return {
    id: row.attempt_id as string,
    snapshot: row.snapshot as OrderSnapshot,
    state: row.state as Attempt['state'],
    session: row.session as CheckoutSession | null,
    hasPaymentEvidence: row.has_payment_evidence as boolean,
    paymentId: row.payment_id as string | null,
    paymentResult: row.payment_result as Attempt['paymentResult'],
    captureResult: row.capture_result as Attempt['captureResult'],
  };
}

/** Construct only when the optional integration is enabled. No connection or schema side effect here. */
export class PostgresAttemptStore implements AttemptStore {
  constructor(private readonly pool: SqlPool, private readonly bindingId: string) {
    if (!bindingId) throw new AirtableError('INVALID_CHECKOUT_BINDING', 503);
  }

  private async one(column: 'record_id' | 'attempt_id' | 'payment_id', value: string): Promise<Attempt | null> {
    const result = await this.pool.query(`SELECT * FROM airtable_checkout_attempts WHERE binding_id=$1 AND ${column}=$2`, [this.bindingId, value]);
    return result.rows[0] ? attemptFromRow(result.rows[0]) : null;
  }
  get(recordId: string) { return this.one('record_id', recordId); }
  getByAttemptId(attemptId: string) { return this.one('attempt_id', attemptId); }
  getByPaymentId(paymentId: string) { return this.one('payment_id', paymentId); }

  // Generated by ACS2 SKILL - Ant International Security
  async withLockedAttempt<T>(attemptId: string, action: (attempt: Attempt) => Promise<T>): Promise<T> {
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      const result = await client.query(
        'SELECT * FROM airtable_checkout_attempts WHERE binding_id=$1 AND attempt_id=$2 FOR UPDATE',
        [this.bindingId, attemptId],
      );
      if (!result.rows[0]) throw new AirtableError('ATTEMPT_NOT_FOUND', 404);
      const value = await action(attemptFromRow(result.rows[0]));
      await client.query('COMMIT');
      return value;
    } catch (error) {
      try { await client.query('ROLLBACK'); } catch { /* Preserve the original error. */ }
      throw error;
    } finally { client.release(); }
  }

  async claim(snapshot: OrderSnapshot, attemptId: string): Promise<{ created: boolean; attempt: Attempt }> {
    const result = await this.pool.query(
      `INSERT INTO airtable_checkout_attempts (attempt_id,binding_id,record_id,order_id,snapshot,state)
       VALUES ($1,$2,$3,$4,$5::jsonb,'creating') ON CONFLICT DO NOTHING RETURNING *`,
      [attemptId, this.bindingId, snapshot.recordId, snapshot.orderId, JSON.stringify(snapshot)],
    );
    if (result.rows[0]) return { created: true, attempt: attemptFromRow(result.rows[0]) };
    const existing = await this.get(snapshot.recordId);
    if (existing) return { created: false, attempt: existing };
    throw new AirtableError('ORDER_REFERENCE_ALREADY_USED', 409);
  }

  async saveSession(attemptId: string, session: CheckoutSession): Promise<Attempt> {
    const result = await this.pool.query(
      `UPDATE airtable_checkout_attempts SET session=$3::jsonb,
       state=CASE WHEN has_payment_evidence THEN 'needs_review' ELSE 'session_ready' END,updated_at=now()
       WHERE binding_id=$1 AND attempt_id=$2 AND session IS NULL AND state IN ('creating','needs_review') RETURNING *`,
      [this.bindingId, attemptId, JSON.stringify(session)],
    );
    if (!result.rows[0]) throw new AirtableError('SESSION_PERSISTENCE_CONFLICT', 503);
    return attemptFromRow(result.rows[0]);
  }

  private async mark(attemptId: string, state: 'unknown' | 'rejected'): Promise<void> {
    await this.pool.query(
      `UPDATE airtable_checkout_attempts SET state=$3,updated_at=now()
       WHERE binding_id=$1 AND attempt_id=$2 AND state='creating' AND NOT has_payment_evidence`,
      [this.bindingId, attemptId, state],
    );
  }
  markUnknown(attemptId: string) { return this.mark(attemptId, 'unknown'); }
  markRejected(attemptId: string) { return this.mark(attemptId, 'rejected'); }

  async recordEvidence(attemptId: string, evidence: PaymentEvidence): Promise<void> {
    const client = await this.pool.connect();
    try {
      await client.query('BEGIN');
      const rows = await client.query(
        'SELECT * FROM airtable_checkout_attempts WHERE binding_id=$1 AND attempt_id=$2 FOR UPDATE',
        [this.bindingId, attemptId],
      );
      if (!rows.rows[0]) throw new AirtableError('NOTIFICATION_ATTEMPT_NOT_FOUND', 409);
      const attempt = attemptFromRow(rows.rows[0]);
      if (attempt.snapshot.amountMinor !== evidence.amountMinor || attempt.snapshot.currency !== evidence.currency) {
        throw new AirtableError('NOTIFICATION_AMOUNT_MISMATCH', 409);
      }
      if (attempt.paymentId && attempt.paymentId !== evidence.paymentId) throw new AirtableError('NOTIFICATION_IDENTITY_MISMATCH', 409);
      // Capture evidence can only attach after a payment notification established the payment ID.
      if (evidence.type === 'CAPTURE_RESULT' && !attempt.paymentId) throw new AirtableError('NOTIFICATION_IDENTITY_MISMATCH', 409);
      await client.query(
        `INSERT INTO airtable_checkout_evidence (binding_id,event_key,attempt_id,evidence)
         VALUES ($1,$2,$3,$4::jsonb) ON CONFLICT (binding_id,event_key) DO NOTHING`,
        [this.bindingId, evidence.eventKey, attemptId, JSON.stringify(evidence)],
      );
      const paymentResult = evidence.type === 'PAYMENT_RESULT' ? mergeEvidenceStatus(attempt.paymentResult, evidence.status) : attempt.paymentResult;
      const captureResult = evidence.type === 'CAPTURE_RESULT' ? mergeEvidenceStatus(attempt.captureResult, evidence.status) : attempt.captureResult;
      await client.query(
        `UPDATE airtable_checkout_attempts SET has_payment_evidence=true,state='needs_review',payment_id=$3,
         payment_result=$4,capture_result=$5,updated_at=now() WHERE binding_id=$1 AND attempt_id=$2`,
        [this.bindingId, attemptId, evidence.paymentId, paymentResult, captureResult],
      );
      await client.query('COMMIT');
    } catch (error) {
      try { await client.query('ROLLBACK'); } catch { /* Preserve the original failure; the caller must not ACK. */ }
      throw error;
    } finally { client.release(); }
  }
}
